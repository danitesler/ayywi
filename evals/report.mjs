#!/usr/bin/env node
// Turns one or more evals/run.mjs results.json files into a markdown table: mean score per task, with the kit vs without,
// and the checks each condition failed most. Usage: node evals/report.mjs <results.json…> [--agent="claude -p …"] > evals/RESULTS.md
import { readFileSync } from "node:fs";

const args = process.argv.slice(2);
const agent = args.find((a) => a.startsWith("--agent="))?.slice("--agent=".length);
const files = args.filter((a) => !a.startsWith("--"));
if (!files.length) {
  console.error('usage: node evals/report.mjs <results.json…> [--agent="claude -p …"]');
  process.exit(2);
}

const all = files.flatMap((f) => JSON.parse(readFileSync(f, "utf8")));
const results = all.filter((r) => !r.error);
const errored = all.length - results.length;
const pct = (x) => `${Math.round(x * 100)}%`;
const mean = (rows) => rows.reduce((s, r) => s + r.score, 0) / (rows.length || 1);
const of = (task, condition) => results.filter((r) => (!task || r.task === task) && r.condition === condition);
const tasks = [...new Set(results.map((r) => r.task))].sort();
const runs = Math.max(...results.map((r) => r.run));

const failures = (condition) => {
  const counts = new Map();
  for (const r of of(null, condition)) for (const name of r.failed) counts.set(name, (counts.get(name) ?? 0) + 1);
  return [...counts].sort((a, b) => b[1] - a[1]).slice(0, 5);
};

const lines = [
  "# Eval results",
  "",
  `Each task asks a coding agent to build one screen with ayywi installed. **With kit**: \`ayywi init\` ran first (skill, AGENTS.md, Cursor rule, lint hook, MCP config). **Without**: the same package, no kit. A run scores the share of its checks that pass: the file exists, \`ayywi lint\` finds no errors and no skipped components, and the task's expected patterns are there (see \`evals/tasks/\`).`,
  "",
  `${tasks.length} task${tasks.length === 1 ? "" : "s"} × ${runs} run${runs > 1 ? "s" : ""} per condition, ${results.length} scored runs${errored ? ` (${errored} more where the agent failed to run are left out)` : ""}${agent ? `. Agent: \`${agent}\`` : ""}. Generated by \`evals/report.mjs\` on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  "| Task | With kit | Without | Difference |",
  "|---|---|---|---|",
  ...tasks.map((t) => {
    const w = mean(of(t, "with-kit"));
    const wo = mean(of(t, "without"));
    return `| ${t} | ${pct(w)} | ${pct(wo)} | ${w - wo >= 0 ? "+" : ""}${Math.round((w - wo) * 100)} pts |`;
  }),
  `| **All** | **${pct(mean(of(null, "with-kit")))}** | **${pct(mean(of(null, "without")))}** | **${Math.round((mean(of(null, "with-kit")) - mean(of(null, "without"))) * 100)} pts** |`,
  "",
  "## Checks failed most",
  "",
  ...["with-kit", "without"].flatMap((c) => [
    `**${c === "with-kit" ? "With kit" : "Without"}**`,
    "",
    ...(failures(c).length ? failures(c).map(([name, n]) => `- ${name}: ${n} of ${of(null, c).length} runs`) : ["- none"]),
    "",
  ]),
  "## Limits",
  "",
  "- The checks are ayywi's own (its linter and expected component names), so this measures how well the kit keeps an agent on ayywi, not whether the UI is better than one built another way.",
  "- Nothing is rendered: no screenshots, no axe. A run can pass every check and still look wrong.",
  "",
];
console.log(lines.join("\n"));
