// tokens/icon-packs/*.json → src/icon-packs.ts, src/css/icon-packs/<id>.css
import { existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { iconNames, loadPacks, packCss, validatePack } from "./lib/icon-packs.mjs";
import { checkMode, finish, output, remove } from "./lib/output.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const packs = loadPacks(root);
const names = iconNames(packs);

const errors = packs.flatMap((p) => validatePack(p, names));
if (errors.length) {
  console.error(`icon packs: ${errors.length} problem(s)\n  ${errors.join("\n  ")}`);
  process.exit(1);
}

const list = (items) => items.map((s) => JSON.stringify(s)).join(", ");

const info = packs
  .map((p) => {
    const fallbacks = names.filter((n) => p.glyphs[n] === null);
    return `  ${JSON.stringify(p.id)}: { label: ${JSON.stringify(p.label)}, description: ${JSON.stringify(p.$description)}, license: ${JSON.stringify(p.license)}, fallbacks: [${list(fallbacks)}] },`;
  })
  .join("\n");

const ts = `// GENERATED by scripts/build-icon-packs.mjs from tokens/icon-packs/ — do not edit by hand.

/** Every glyph name an icon pack replaces: the glyphs ayywi draws, plus common app icons. Each pack maps these names to its own glyphs. */
export const iconNames = [${list(names)}] as const;
export type IconName = (typeof iconNames)[number];

/** Icon packs shipped as @danitesler/ayywi/icons/<id>.css (from tokens/icon-packs/). The default, hugeicons, comes first. */
export const iconPacks = [${list(packs.map((p) => p.id))}] as const;
export type IconPackName = (typeof iconPacks)[number];

export interface IconPackInfo {
  readonly label: string;
  readonly description: string;
  readonly license: string;
  /** Glyphs the pack doesn't have; the default pack's glyph is drawn instead. */
  readonly fallbacks: readonly IconName[];
}

export const iconPackInfo: Record<IconPackName, IconPackInfo> = {
${info}
};
`;

output(join(root, "src/icon-packs.ts"), ts);

const cssDir = join(root, "src/css/icon-packs");
for (const p of packs) output(join(cssDir, `${p.id}.css`), packCss(p, names, root));
for (const f of existsSync(cssDir) ? readdirSync(cssDir) : []) {
  if (!packs.some((p) => `${p.id}.css` === f)) remove(join(cssDir, f));
}
finish("icon packs");
if (!checkMode) console.log(`icon packs: ${packs.map((p) => p.id).join(", ")}; ${names.length} glyph names`);
